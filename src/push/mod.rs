//! 上报侧：把「已确认的行」变成「带身份的载荷」，再交给网关。
//!
//! - [`idempotency`]：上报身份 —— 幂等键（哪一条业务记录）与载荷摘要（这份载荷有没有变）；
//!   同一个幂等键下摘要变了就是订正（修订号 +1），摘要没变就是重复提交（不重复推送）。
//! - [`client`]：院内卫健上报网关出站客户端 —— 真实协议（路径 / 头 / 报文字段全集）、
//!   状态码语义分类（受理 / 退回 / 可重试 / 回执不可用）；凭据只从环境变量读。
//! - [`dept`]：院内 HIS 科室主数据目录出站客户端 —— 真实读协议（路径 / 头 / 响应字段），
//!   拉不到就降级（跳过科室一致性检查 + 标「科室主数据未校验」），缓存兜底并标注数据时间。
//! - [`program`]：上报提交计划编译器 —— 把一批行编成**有条件的批量提交程序**
//!   （第 i 步只在第 i-1 步成功后执行），并给出「已跳过」与「待人工判定」两张清单。
//! - [`executor`]：条件批量执行器 —— 逐步执行、失败分类（可重试 5xx / 不可重试 4xx /
//!   幂等命中 / 网络超时）、批末条件回滚（**只回滚批次汇总**，行级回执不回滚）。
//! - [`receipt`]：回执解析与行级状态推进 —— 回执是状态推进的唯一依据；
//!   幂等键 ↔ 回执 ID 一一对应，退回的错误码与字段名写回原表说明列。
//! - [`retry`]：退避重试与断点续跑 —— 5xx / 超时指数退避重试（4xx 不重试），
//!   断点续跑不重复推送已成功的行，重试耗尽的行进待办清单。
//! - [`status`]：行级上报状态取值 —— **单一出处**（已上报 / 被退回 / 待重试 …）。
//! - [`batch`]：批次汇总 —— **口径定义**（已上报 / 被退回 / 待重试 / 问题项数 四项）
//!   与汇总落库（一次事务；批末回滚时汇总回批前值）。
//! - [`gate`]：写闸门的执行点 —— 推之前先问「这一行确认过没有」，没过闸门**一个字节都不发**。
//! - [`send`]：上报发送 —— 把上面几层接成一条链（恢复台账 → 过闸门 → 逐步执行 → 落库），
//!   执行与落库分两段（写闸门要读状态库，落库要写状态库，同一个库不能同时借两次）。
//!
//! 载荷与报文的字段全集见 `spec.md`「出站报文（正式对接规范）」。

