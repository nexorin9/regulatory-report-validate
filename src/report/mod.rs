//! 报告与举证层：经办人能直接带走、拿去核对的东西。
//!
//! 分两段：
//! - [`summary`]：问题清单汇总（按行 / 按问题类型两个维度）与**校验结论取值规则**；
//! - [`evidence`]：每行依据举证包 —— 这一行命中了哪些规则、按哪条官方口径、该怎么改；
//! - [`pending`]：未上报名单与催报对照 —— 还剩哪些行没报上去、谁还没交表；
//! - [`receipt`]：回执台账 —— 已经报的那部分，凭哪条身份、报的是哪一版数据、网关认了没有；
//! - [`diff`]：口径差异清单 —— 换版前两版口径到底哪几条不一样、前后取值是什么。
//!
//! # 为什么不并进规则层
//!
//! 规则层只回答「这一行有没有违反哪条口径」，不回答「这一批一共哪几类问题」
//! 与「这一行该怎么改」。后两件事是给**人**看的产物：经办人拿给科室、科室照着改。
//! 放在独立一层，口径规则改了，产物层不用跟着改；产物层的口径调整也不动规则。

pub mod diff;
pub mod evidence;
pub mod pending;
pub mod receipt;
pub mod summary;
