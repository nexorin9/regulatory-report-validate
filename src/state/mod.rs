//! 状态与确认层：行级状态机、人工确认流、审计链。
//!
//! 本层回答三个问题：
//!
//! - **这一行现在到哪一步了** —— [`machine`]：行级状态机（待校验 → 校验通过 → 待确认 →
//!   已上报 / 被退回 / 待重试）。合法迁移表是白名单，非法迁移被拒绝并报错，状态不被静默改写；
//! - **这一行谁确认过** —— [`confirm`]：确认记录与上报写闸门（未确认不推）；
//! - **这些动作怎么回放** —— [`audit`]：append-only 审计链，可按行与按批次回放。
//!
//! 三件事分三个模块，但**状态推进只有一个入口**：[`machine::advance`]。

pub mod audit;
pub mod confirm;
pub mod machine;
