//! 口径检查器。
//!
//! 四类检查器各占一个模块：
//!
//! | 模块 | 管什么 | 任务 |
//! |---|---|---|
//! | [`required`] | 五列必填、比率型指标条件必填、表内业务主键唯一 | Task 10 |
//! | [`enum_`] | 枚举越界四类（报告期格式 / 报告期类型 / 指标编号 / 科室代码目录）与按指标类别判定的条件必填 | Task 11 |
//! | [`unit`] | 计量单位值域检查（`R-ENUM-003`）、单位与指标口径匹配（`R-UNIT-001`）、单位别名归一 | Task 12 |
//! | [`formula`] | 分子分母公式复算（`R-FORMULA-001`）、分母为 0（`R-FORMULA-002`）、数值形态（`R-FORMULA-003`） | Task 13 |
//!
//! 指标类别（在册编号、比率型 / 人均负担型）查 [`crate::rules::indicators`] ——
//! 官方 27 项口径登记表是名单的唯一出处，各检查器不再各写一份。
//!
//! # 检查器不执行规则，只编译规则
//!
//! 检查器把「口径」编译成 [`crate::rules::model::Rule`]（SQL 文本 + 命名参数 + 依据 + 版本），
//! 由参数化执行器 [`crate::rules::executor`] 统一执行。这样口径仍是**数据**：
//! SQL 文本与比较用的取值分开存放，取值走绑定参数，规则表里改一个取值不用改代码。
//!
//! 每个检查器都要满足三条：
//!
//! 1. **口径有出处**：每条规则带官方依据（`basis`），缺依据的规则拒绝装载；
//! 2. **边界写清楚**：空值语义、异常分支（分母为 0、缺列、语法错）都有确定结论，不静默通过；
//! 3. **可独立验收**：检查器编译出的规则能单独跑出可核对的问题清单。

pub mod enum_;
pub mod formula;
pub mod required;
pub mod unit;
